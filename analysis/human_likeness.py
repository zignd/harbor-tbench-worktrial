"""Human-likeness of generated tasks vs the hand-written examples (stretch goal D).

Three views:
- stylometrics(): instruction length, sentences, bullets, headers, emphasis,
  code spans; test count; Dockerfile and solution size. Bercovich's guideline
  says LLM-written instructions are "verbose, over-structured" and full of
  emphasis, so these are the tells.
- discrimination(): blinded pairs (one example, one generated), shuffled; a
  Sonnet judge guesses which instruction a person wrote. Accuracy near 50%
  means the generated ones are indistinguishable.
- The same `harbor check` rubric is run on both sets (evaluator/quality.py) so
  test thoroughness and polish are compared on identical criteria.
"""

import random
import re
from pathlib import Path

from analysis.llm import chat, extract_json


def _canary_free(text: str) -> str:
    return re.sub(
        r"^\s*(<!--.*?-->|#.*canary.*)\s*$", "", text, flags=re.IGNORECASE | re.MULTILINE
    ).strip()


def stylometrics(task_dir: Path) -> dict:
    task_dir = Path(task_dir)
    inst = _canary_free((task_dir / "instruction.md").read_text())
    tests = (task_dir / "tests" / "test_outputs.py").read_text(errors="replace")
    docker = (task_dir / "environment" / "Dockerfile").read_text(errors="replace")
    solve = (task_dir / "solution" / "solve.sh").read_text(errors="replace")
    env_files = [p for p in (task_dir / "environment").rglob("*") if p.is_file()]
    return {
        "instruction_words": len(inst.split()),
        "instruction_sentences": len(re.findall(r"[.!?](\s|$)", inst)),
        "instruction_bullets": len(re.findall(r"^\s*([-*]|\d+\.)\s", inst, re.MULTILINE)),
        "instruction_headers": len(re.findall(r"^\s*#{1,6}\s", inst, re.MULTILINE)),
        "instruction_emphasis": len(re.findall(r"\*\*|__|\bIMPORTANT\b|\bMUST\b|\bNOTE\b", inst)),
        "instruction_code_spans": inst.count("`") // 2,
        "test_functions": len(re.findall(r"^def test_", tests, re.MULTILINE)),
        "dockerfile_lines": len([line for line in docker.splitlines() if line.strip()]),
        "solution_lines": len([line for line in solve.splitlines() if line.strip()]),
        "environment_files": len(env_files),
    }


DISCRIMINATION_PROMPT = """Two task instructions for a command-line benchmark are shown. One was written by a human
engineer; the other was generated by an AI. Which one did the human write?

Instruction A:
<<<
{a}
>>>

Instruction B:
<<<
{b}
>>>

Return only JSON: {{"human": "A" or "B", "confidence": 0-1, "tells": "what gave it away"}}"""


def discrimination(
    human_dirs: list[Path], generated_dirs: list[Path], seed: int = 0, chat_fn=chat
) -> dict:
    """Blinded pairwise test. Returns accuracy, per-pair guesses, cost."""
    rng = random.Random(seed)
    pairs = [(h, g) for h in human_dirs for g in generated_dirs]
    rng.shuffle(pairs)
    correct, rows, cost = 0, [], 0.0
    for human, generated in pairs:
        h_text = _canary_free((Path(human) / "instruction.md").read_text())
        g_text = _canary_free((Path(generated) / "instruction.md").read_text())
        human_is_a = rng.random() < 0.5
        a, b = (h_text, g_text) if human_is_a else (g_text, h_text)
        reply = chat_fn(DISCRIMINATION_PROMPT.format(a=a, b=b), max_tokens=600, temperature=0.0)
        cost += reply.cost_usd
        guess = extract_json(reply.text).get("human", "")
        hit = (guess == "A") == human_is_a
        correct += hit
        rows.append(
            {
                "human": Path(human).name,
                "generated": Path(generated).name,
                "correct": hit,
                "guess": guess,
            }
        )
    return {"accuracy": correct / len(pairs) if pairs else 0.0, "pairs": rows, "cost_usd": cost}
