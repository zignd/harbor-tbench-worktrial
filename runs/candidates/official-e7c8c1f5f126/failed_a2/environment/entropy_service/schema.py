"""
schema.py - Data definitions and result schemas for the entropy audit pipeline.

Defines namedtuples, dataclasses and constants used across the audit modules.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field, asdict
from typing import Optional, List


# ── Constants ─────────────────────────────────────────────────────────────────

PIPELINE_VERSION = "1.3.0"
DEFAULT_WINDOW_SIZE: int = 512
DEFAULT_HOP_SIZE: int = 256
DEFAULT_FFT_SIZE: int = 512
DEFAULT_N_FREQ_BINS: int = 256
MAX_WINDOWS_DEFAULT: int = 2000

ENTROPY_LOW_WARN: float = 7.50
ENTROPY_DEGENERATE: float = 1.00
ENTROPY_NOMINAL_LOW: float = 7.80
ENTROPY_NOMINAL_HIGH: float = 8.05


# ── Result types ──────────────────────────────────────────────────────────────

@dataclass
class WindowResult:
    """Per-window entropy result."""
    window_index: int
    start_byte: int
    end_byte: int
    spectral_entropy: float
    is_degenerate: bool = False

    def to_dict(self):
        return asdict(self)


@dataclass
class SourceAuditResult:
    """Aggregated audit result for a single source."""
    source_id: str
    pipeline_version: str
    n_windows: int
    n_degenerate: int
    min_entropy: float
    max_entropy: float
    mean_entropy: float
    std_entropy: float
    calibration_offset: float = 0.0
    calibration_applied: bool = False
    window_results: List[WindowResult] = field(default_factory=list)
    status: str = "UNKNOWN"
    notes: List[str] = field(default_factory=list)

    def to_dict(self):
        d = asdict(self)
        return d

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), indent=indent)


@dataclass
class CalibrationRecord:
    """Stored calibration data for a source."""
    source_id: str
    offset: float
    n_reference_windows: int
    reference_mean_entropy: float
    pipeline_version: str

    def to_dict(self):
        return asdict(self)


# ── Source config ─────────────────────────────────────────────────────────────

@dataclass
class SourceConfig:
    """Configuration for a monitored entropy source."""
    source_id: str
    data_dir: Optional[str] = None
    window_size: int = DEFAULT_WINDOW_SIZE
    hop_size: int = DEFAULT_HOP_SIZE
    fft_size: int = DEFAULT_FFT_SIZE
    n_freq_bins: int = DEFAULT_N_FREQ_BINS
    max_windows: int = MAX_WINDOWS_DEFAULT
    enabled: bool = True
    alert_on_degenerate: bool = True
    expected_entropy_low: float = ENTROPY_NOMINAL_LOW
    expected_entropy_high: float = ENTROPY_NOMINAL_HIGH

    @classmethod
    def from_dict(cls, d: dict) -> "SourceConfig":
        return cls(**{k: v for k, v in d.items() if k in cls.__dataclass_fields__})


# ── Alert definitions ─────────────────────────────────────────────────────────

@dataclass
class Alert:
    """An alert generated by the pipeline."""
    source_id: str
    severity: str  # 'INFO', 'WARN', 'ERROR', 'CRITICAL'
    message: str
    affected_windows: List[int] = field(default_factory=list)
    metadata: dict = field(default_factory=dict)

    def __str__(self):
        return f"[{self.severity}] {self.source_id}: {self.message}"


ALERT_SEVERITY_ORDER = {"INFO": 0, "WARN": 1, "ERROR": 2, "CRITICAL": 3}


def alert_severity_key(alert: Alert) -> int:
    return ALERT_SEVERITY_ORDER.get(alert.severity, -1)


# ── Serialisation helpers ─────────────────────────────────────────────────────

def result_to_json(result: SourceAuditResult, path: Optional[str] = None) -> str:
    """Serialise a SourceAuditResult to JSON."""
    text = result.to_json()
    if path:
        with open(path, "w") as f:
            f.write(text)
    return text


def load_source_configs(path: str) -> List[SourceConfig]:
    """Load source configurations from a JSON file."""
    with open(path) as f:
        data = json.load(f)
    return [SourceConfig.from_dict(item) for item in data.get("sources", [])]
