"""Calibrate gated candidates against Opus 4.8 and ship the learnable ones.

    uv run --env-file .env python -m scripts.calibrate_candidates [--only ID ...] [--max N]

For each candidate in runs/candidates/ whose status is "gated" and that has no
calibration yet: run evaluator.calibrate.calibrate(), save calibration.json,
and if the verdict is "learnable", copy the task to output/<slug>/ with a
README.md describing it and why the model fails it (from the failure judge).
Shipping refuses to run in dev mode (config.assert_official_models).
"""

import argparse
import json
import shutil
from pathlib import Path

from analysis.ledger import Ledger
from evaluator.calibrate import LEGIT_PASS, VALID_FAIL, calibrate
from generator.config import EVAL_MODEL, MODEL, MODEL_LABEL, OUTPUT_DIR, assert_official_models
from generator.pipeline import CANDIDATES_DIR, Candidate, stage_redteam
from generator.spec import TaskSpec

README = """# {title}

{scenario}

## What it tests
{failure_modes}

## Models
Authored, reviewed and judged by `{model}`; calibrated by terminus-2 + `{eval_model}`. The 1-3 of 5
band is relative to that calibration model.

## Calibration (terminus-2 + {eval_model})
{passes} of {n} judged runs passed ({verdict}; runs stop once the 5-run verdict is certain).

## Why the model fails it
{why}

## Verification
{tests}

Generated by this repo's pipeline (spec `{spec_id}`); see runs/candidates/{cand_id}/.
"""


def ship(cand_dir: Path, cal: dict) -> Path:
    assert_official_models()
    bp = json.loads((cand_dir / "blueprint.json").read_text())
    dest = Path(OUTPUT_DIR) / bp["slug"]
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(cand_dir / "task", dest)
    fails = [t["failure"] for t in cal["trials"] if t.get("outcome") == VALID_FAIL]
    why = "\n".join(f"- {f['mode']}: {f['explanation']}" for f in fails) or "- (none recorded)"
    (dest / "README.md").write_text(
        README.format(
            model=MODEL,
            eval_model=EVAL_MODEL,
            title=bp["title"],
            scenario=bp["scenario"],
            failure_modes="\n".join(f"- {m}" for m in bp["expected_failure_modes"]),
            passes=sum(o == LEGIT_PASS for o in cal["outcomes"]),
            n=len(cal["outcomes"]),
            verdict=cal["verdict"],
            why=why,
            tests="\n".join(f"- {t}" for t in bp["tests"]),
            spec_id=json.loads((cand_dir / "spec.json").read_text()).get("topic") or cand_dir.name,
            cand_id=cand_dir.name,
        )
    )
    return dest


def _slug(cand_dir: Path) -> str:
    return json.loads((cand_dir / "blueprint.json").read_text())["slug"]


def calibrate_one(cand_dir: Path, ledger) -> dict | None:
    """Red-team (if never run), calibrate and ship one gated candidate. Returns the record."""
    status_file = cand_dir / "status.json"
    if not list(cand_dir.glob("redteam_a*.json")):
        # Gated before the red-team gate existed: run it now, before any Opus spend.
        cand = Candidate(
            TaskSpec(**json.loads((cand_dir / "spec.json").read_text())), cand_id=cand_dir.name
        )
        problems = stage_redteam(cand, ledger, attempt=0)
        if problems:
            status_file.write_text(json.dumps({"status": "hackable", "problems": problems}))
            print(f"{cand_dir.name}  red-team found an exploit; not calibrated", flush=True)
            return None
    existing = cand_dir / "calibration.json"
    if existing.exists():
        # Calibrated during its gates (CALIBRATE_FIRST): ship if learnable, never recalibrate.
        record = json.loads(existing.read_text())
        if record["verdict"] == "learnable" and not (Path(OUTPUT_DIR) / _slug(cand_dir)).exists():
            print(f"{cand_dir.name}  learnable -> {ship(cand_dir, record)}", flush=True)
        return record
    cal = calibrate(cand_dir / "task", cand_dir.name, ledger)
    record = {
        "verdict": cal.verdict,
        "outcomes": cal.outcomes,
        "trials": cal.trials,
        "cost_usd": round(cal.cost_usd, 4),
        "models": MODEL_LABEL,
    }
    (cand_dir / "calibration.json").write_text(json.dumps(record, indent=1, default=str))
    shipped = ship(cand_dir, record) if cal.verdict == "learnable" else None
    print(
        f"{cand_dir.name}  {cal.summary}  ${cal.cost_usd:.2f}"
        + (f"  -> {shipped}" if shipped else ""),
        flush=True,
    )
    return record


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--only", nargs="*", help="candidate ids to calibrate")
    parser.add_argument("--max", type=int, default=100, help="max candidates this run")
    args = parser.parse_args()
    ledger = Ledger()
    done = 0
    for cand_dir in sorted(CANDIDATES_DIR.iterdir()):
        status_file = cand_dir / "status.json"
        if args.only and cand_dir.name not in args.only:
            continue
        if not status_file.exists() or json.loads(status_file.read_text())["status"] != "gated":
            continue
        if (cand_dir / "calibration.json").exists() or done >= args.max:
            continue
        if calibrate_one(cand_dir, ledger) is not None:
            done += 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
